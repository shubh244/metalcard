/** Seed catalog: original CardForge copy + official issuer apply hubs. */
export const cards: CreditCard[] = [...seedCards, ...moreCards];

export { BANK_APPLY };

export function getCardBySlug(slug: string): CreditCard | undefined {
  return cards.find((c) => c.slug === slug);
}

export function getCardById(id: string): CreditCard | undefined {
  return cards.find((c) => c.id === id);
}

export function getBanks(): { id: string; name: string; count: number }[] {
  const map = new Map<string, { id: string; name: string; count: number }>();
  for (const c of cards) {
    const existing = map.get(c.bankId);
    if (existing) existing.count += 1;
    else map.set(c.bankId, { id: c.bankId, name: c.bankName, count: 1 });
  }
  return Array.from(map.values()).sort((a, b) => a.name.localeCompare(b.name));
}

export function getCardsByBank(bankId: string): CreditCard[] {
  return cards.filter(
    (c) => c.bankId.toLowerCase() === bankId.toLowerCase()
  );
}
