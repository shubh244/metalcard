type Draft = Omit<
  CreditCard,
  | "status"
  | "gst"
  | "fees"
  | "rewards"
  | "lounge"
  | "eligibility"
  | "milestones"
  | "scores"
  | "seoTitle"
  | "seoDescription"
> & {
  fees: Partial<CreditCard["fees"]> &
    Pick<CreditCard["fees"], "joiningFee" | "renewalFee">;
  rewards: Partial<CreditCard["rewards"]> &
    Pick<CreditCard["rewards"], "rewardType" | "rewardName" | "earnRate">;
  lounge?: Partial<CreditCard["lounge"]>;
  eligibility?: Partial<CreditCard["eligibility"]>;
  milestones?: CreditCard["milestones"];
  scores: CreditCard["scores"];
};

function card(d: Draft): CreditCard {
  return {
    id: d.id,
    bankId: d.bankId,
    bankName: d.bankName,
    name: d.name,
    slug: d.slug,
    status: "Active",
    category: d.category,
    premiumLevel: d.premiumLevel,
    network: d.network,
    variant: d.variant,
    coBrand: d.coBrand,
    applyType: d.applyType,
    targetUser: d.targetUser,
    bestFor: d.bestFor,
    pros: d.pros,
    cons: d.cons,
    fees: {
      joiningFee: d.fees.joiningFee,
      renewalFee: d.fees.renewalFee,
      gstApplicable: d.fees.gstApplicable ?? true,
      renewalWaiver: d.fees.renewalWaiver ?? true,
      waiverTarget: d.fees.waiverTarget ?? null,
      forexMarkup: d.fees.forexMarkup ?? 3.5,
      addOnCardFee: d.fees.addOnCardFee ?? 0,
    },
    rewards: {
      rewardType: d.rewards.rewardType,
      rewardName: d.rewards.rewardName,
      earnRate: d.rewards.earnRate,
      earnRateNumeric: d.rewards.earnRateNumeric ?? 1,
      redemptionValue: d.rewards.redemptionValue ?? 0.25,
      transferPartners: d.rewards.transferPartners ?? [],
      expiry: d.rewards.expiry ?? "As per issuer",
      bonusPoints: d.rewards.bonusPoints ?? "",
      cashbackRules: d.rewards.cashbackRules ?? [],
    },
    lounge: {
      domestic: d.lounge?.domestic ?? "Limited / none",
      international: d.lounge?.international ?? "No",
      priorityPass: d.lounge?.priorityPass ?? false,
      guestAccess: d.lounge?.guestAccess ?? false,
    },
    eligibility: {
      minAge: d.eligibility?.minAge ?? 21,
      maxAge: d.eligibility?.maxAge ?? 65,
      salariedMinIncome: d.eligibility?.salariedMinIncome ?? 25000,
      selfEmployedNote:
        d.eligibility?.selfEmployedNote ?? "ITR / bank statement as required",
      creditScore: d.eligibility?.creditScore ?? 700,
      note: d.eligibility?.note ?? "Subject to issuer policy",
    },
    milestones: d.milestones ?? [],
    scores: d.scores,
    metalTone: d.metalTone,
    applyUrl: d.applyUrl || BANK_APPLY[d.bankId] || "https://www.rbi.org.in/",
    seoTitle: `${d.name} — Fees, Rewards & Benefits | CardForge`,
    seoDescription: `Compare ${d.name}: joining fee, rewards, lounge access and eligibility. Illustrative CardForge summary — verify on the bank site.`,
  };
}

